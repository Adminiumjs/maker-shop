/** One engine's words for the old schema's types. */
interface Words {
  q: (name: string) => string;
  id: string;
  text: (length: number) => string;
  json: string;
  moment: string;
  now: string;
  /** How a JSON value is written in an INSERT. */
  jsonValue: (text: string) => string;
}

const WORDS: Record<Engine, Words> = {
  sqlite: { q: (n) => `"${n}"`, id: "INTEGER PRIMARY KEY", text: () => "TEXT", json: "TEXT", moment: "TEXT", now: "CURRENT_TIMESTAMP", jsonValue: (t) => `'${t}'` },
  postgres: { q: (n) => `"${n}"`, id: "integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", text: () => "text", json: "jsonb", moment: "timestamptz", now: "now()", jsonValue: (t) => `'${t}'::jsonb` },
  mysql: { q: (n) => `\`${n}\``, id: "INT AUTO_INCREMENT PRIMARY KEY", text: (n) => `VARCHAR(${String(n)})`, json: "JSON", moment: "DATETIME", now: "CURRENT_TIMESTAMP", jsonValue: (t) => `'${t}'` },
};

