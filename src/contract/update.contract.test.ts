        ok(await staff.put("/api/v1/public-api", { enabled: true }));
        ok(await staff.put("/api/v1/settings/email", { publicOrigin: server.base }));
        const served = ok(await new Caller(server.base).get<{ publishableKey: string; publicKeys?: Record<string, string>; tables?: Record<string, string> }>("/apps/maker/customer/surface-config.json"));
        expect(served.tables?.["orders"]).toBe("maker_orders");
        const originFetch: typeof fetch = (input, init) => {
          const headers = new Headers(init?.headers);
          headers.set("origin", server.base);
          return fetch(input, { ...init, headers });
        };
        const door = new AdminiumShop({ baseUrl: server.base, publishableKey: served.publishableKey, ...(served.tables === undefined ? {} : { tables: served.tables }), ...(served.publicKeys === undefined ? {} : { publicKeys: served.publicKeys }) }, { fetch: originFetch });
        const catalogue = await door.catalogue();
        useShop.setState({ catalogue });
        const p = catalogue.products.find((x) => x.code === "coast-wal");
        expect(p, `the shop's catalogue: ${JSON.stringify(catalogue.products.map((x) => x.code))}`).toBeDefined();
        if (p === undefined) return;
        const first = (kind: string) => catalogue.options.filter((o) => String(o.productId) === String(p.id) && o.kind === kind)[0]?.id ?? null;
